const LuauGenerator = {};

/**
 * Generates all Luau scripts for the given target and writes them to buildRoot.
 *
 * @param {object} opts
 * @param {string}  opts.buildRoot   - absolute build output root
 * @param {object}  opts.target      - resolved target spec
 * @param {object}  opts.auditLedger - k1 audit reference
 * @returns {Promise<{ok: boolean, files: string[], error?: string}>}
 */
LuauGenerator.generate = async function({ buildRoot, target, auditLedger }) {
  if (!buildRoot || !target) {
    throw new Error("[LuauGenerator] buildRoot and target are required");
  }

  const targetId   = target.id;
  const targetSpec = target;
  const generated  = [];

  try {
    auditLedger?.log("LuauGenerator.generate.start", "INFO", { buildRoot, targetId });

    const manifest = _buildScriptManifest(targetId, targetSpec);

    for (const entry of manifest) {
      const absPath = path.join(buildRoot, entry.relPath);
      const content = entry.generator();
      if (content === null || content === undefined) continue;
      await mkdir(path.dirname(absPath), { recursive: true });
      await writeFile(absPath, content, "utf8");
      generated.push(entry.relPath);
    }

    auditLedger?.log("LuauGenerator.generate.complete", "INFO", {
      buildRoot,
      targetId,
      filesGenerated: generated.length,
    });

    return { ok: true, files: generated };

  } catch (err) {
    auditLedger?.log("LuauGenerator.generate.error", "ERROR", {
      buildRoot,
      targetId,
      error: err.message,
    });
    return { ok: false, files: generated, error: err.message };
  }
};

/**
 * Injects the AF51Runtime Luau modules into the build.
 * Copies from the source runtime/ directory to build/ReplicatedStorage/Packages/AF51Runtime/.
 *
 * @param {object} opts
 * @param {string}  opts.buildRoot      - absolute build output root
 * @param {string}  opts.runtimeSrcDir  - absolute path to source runtime/ dir
 * @param {object}  opts.auditLedger
 * @returns {Promise<{ok: boolean, files: string[], error?: string}>}
 */
LuauGenerator.injectRuntime = async function({ buildRoot, runtimeSrcDir, auditLedger }) {
  const runtimeModules = [
    "event-bus.lua",
    "state-store.lua",
    "service-registry.lua",
    "runtime-init.lua",
    "network-layer.lua",
    "audit-runtime.lua",
    "permission-layer.lua",
  ];

  // Rojo naming: Rojo uses the filename stem as the ModuleScript name.
  // We rename to PascalCase to match require() paths used in generated scripts.
  const nameMap = {
    "event-bus.lua":        "EventBus.lua",
    "state-store.lua":      "StateStore.lua",
    "service-registry.lua": "ServiceRegistry.lua",
    "runtime-init.lua":     "RuntimeInit.lua",
    "network-layer.lua":    "NetworkLayer.lua",
    "audit-runtime.lua":    "AuditRuntime.lua",
    "permission-layer.lua": "PermissionLayer.lua",
  };

  const destDir  = path.join(buildRoot, "src/ReplicatedStorage/Packages/AF51Runtime");
  const injected = [];

  try {
    for (const srcFile of runtimeModules) {
      const srcPath  = path.join(runtimeSrcDir, srcFile);
      const destName = nameMap[srcFile];
      const destPath = path.join(destDir, destName);

      if (!existsSync(srcPath)) {
        throw new Error(`Runtime source file not found: ${srcPath}`);
      }

      await copyFile(srcPath, destPath);
      injected.push(`src/ReplicatedStorage/Packages/AF51Runtime/${destName}`);
    }

    auditLedger?.log("LuauGenerator.injectRuntime.complete", "INFO", {
      injected: injected.length,
    });

    return { ok: true, files: injected };

  } catch (err) {
    auditLedger?.log("LuauGenerator.injectRuntime.error", "ERROR", { error: err.message });
    return { ok: false, files: injected, error: err.message };
  }
};

