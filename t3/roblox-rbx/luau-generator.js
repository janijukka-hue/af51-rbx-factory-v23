function _fpsKit(_targetId) {
  return `--!strict
--[[
	FPSKit  ·  AF51 RBX — gameplay module for "fps" targets
	================================================================
	Wires the two-team arena emitted by v2: ensures Blue/Red Teams,
	repurposes TeamSpawn parts as SpawnLocations, gives WeaponLocker
	prompts that hand out a basic blaster Tool, scores flag captures
	(touch by enemy team), and runs a CapturePoint that scores after
	CaptureTime seconds of single-team occupancy. Runs a match round
	with a score cap and a duration timer, replicates match state +
	a KillFeed RemoteEvent to clients via ReplicatedStorage.FPSEvents,
	and parents a BillboardGui to each CapturePoint showing the
	holding team colour and capture progress.

	TAGS:
	  • "TeamSpawn"     Attr Team:string ("Blue"|"Red")
	  • "Flag"          Attrs Team, ObjectiveKind
	  • "WeaponLocker"  Attr Team
	  • "Cover"         (no attrs) — geometry only
	  • "CapturePoint"  Attrs CaptureTime, ObjectiveKind
]]

local CollectionService = game:GetService("CollectionService")
local Players           = game:GetService("Players")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local RunService        = game:GetService("RunService")
local ServerStorage     = game:GetService("ServerStorage")
local Teams             = game:GetService("Teams")
local Workspace         = game:GetService("Workspace")

local FPSKit = {}
local started = false
local teams: { [string]: Team } = {}
local flagHome: { [BasePart]: CFrame } = {}

local TEAM_COLORS = {
	Blue = BrickColor.new("Bright blue"),
	Red  = BrickColor.new("Bright red"),
}
local TEAM_COLOR3 = {
	Blue = Color3.fromRGB(13, 105, 172),
	Red  = Color3.fromRGB(196, 40, 28),
}

local MATCH_SCORE_CAP = 500
local MATCH_DURATION  = 600       -- seconds (10 min)
local INTERMISSION    = 15        -- seconds between rounds

local matchState: Configuration? = nil
local killFeed: RemoteEvent? = nil
local matchOver = false

local function attr(inst: Instance, name: string, default: any): any
	local v = inst:GetAttribute(name)
	if v == nil then return default end
	return v
end

local function ensureTeam(name: string): Team
	if teams[name] then return teams[name] end
	local team = Teams:FindFirstChild(name) :: Team?
	if not team then
		team = Instance.new("Team")
		team.Name = name
		team.TeamColor = TEAM_COLORS[name] or BrickColor.new("Medium stone grey")
		team.AutoAssignable = false
		team.Parent = Teams
	end
	teams[name] = team :: Team
	return team :: Team
end

local function ensureStats(player: Player): (IntValue, IntValue, IntValue)
	local leaderstats = player:FindFirstChild("leaderstats") :: Folder?
	if not leaderstats then
		leaderstats = Instance.new("Folder")
		leaderstats.Name = "leaderstats"
		leaderstats.Parent = player
	end
	local function intStat(name: string, default: number): IntValue
		local v = leaderstats:FindFirstChild(name) :: IntValue?
		if not v then
			v = Instance.new("IntValue"); v.Name = name; v.Value = default; v.Parent = leaderstats
		end
		return v :: IntValue
	end
	return intStat("Captures", 0), intStat("Score", 0), intStat("Kills", 0)
end

local function smallerTeamName(): string
	local count = { Blue = 0, Red = 0 }
	for _, player in Players:GetPlayers() do
		if player.Team and count[player.Team.Name] then
			count[player.Team.Name] = count[player.Team.Name] + 1
		end
	end
	if count.Blue <= count.Red then return "Blue" end
	return "Red"
end

local function ensureSharedState()
	local folder = ReplicatedStorage:FindFirstChild("FPSEvents") :: Folder?
	if not folder then
		folder = Instance.new("Folder")
		folder.Name = "FPSEvents"
		folder.Parent = ReplicatedStorage
	end
	local feed = folder:FindFirstChild("KillFeed") :: RemoteEvent?
	if not feed then
		feed = Instance.new("RemoteEvent")
		feed.Name = "KillFeed"
		feed.Parent = folder
	end
	killFeed = feed
	local state = folder:FindFirstChild("MatchState") :: Configuration?
	if not state then
		state = Instance.new("Configuration")
		state.Name = "MatchState"
		state.Parent = folder
	end
	state:SetAttribute("BlueScore", 0)
	state:SetAttribute("RedScore", 0)
	state:SetAttribute("Winner", "")
	state:SetAttribute("ScoreCap", MATCH_SCORE_CAP)
	state:SetAttribute("MatchEndsAt", os.time() + MATCH_DURATION)
	matchState = state
end

local function pushFeed(message: string, teamName: string?)
	if not killFeed then return end
	(killFeed :: RemoteEvent):FireAllClients(message, teamName or "")
end

local function teamScoreAttr(teamName: string): string
	return teamName .. "Score"
end

local function endMatch()
	if matchOver or not matchState then return end
	matchOver = true
	local blue = tonumber((matchState :: Configuration):GetAttribute("BlueScore")) or 0
	local red  = tonumber((matchState :: Configuration):GetAttribute("RedScore"))  or 0
	local winner = (blue == red) and "Draw" or (blue > red and "Blue" or "Red")
	;(matchState :: Configuration):SetAttribute("Winner", winner)
	pushFeed(("MATCH OVER — %s wins  (Blue %d : %d Red)"):format(winner, blue, red), winner)
	task.delay(INTERMISSION, function()
		if not matchState then return end
		;(matchState :: Configuration):SetAttribute("BlueScore", 0)
		;(matchState :: Configuration):SetAttribute("RedScore", 0)
		;(matchState :: Configuration):SetAttribute("Winner", "")
		;(matchState :: Configuration):SetAttribute("MatchEndsAt", os.time() + MATCH_DURATION)
		matchOver = false
		pushFeed("New match started.", nil)
	end)
end

local function addTeamScore(teamName: string, delta: number)
	if matchOver or not matchState then return end
	local key = teamScoreAttr(teamName)
	local cur = tonumber((matchState :: Configuration):GetAttribute(key)) or 0
	local nxt = cur + delta
	;(matchState :: Configuration):SetAttribute(key, nxt)
	if nxt >= MATCH_SCORE_CAP then endMatch() end
end

local function tickMatch()
	if matchOver or not matchState then return end
	local endsAt = tonumber((matchState :: Configuration):GetAttribute("MatchEndsAt")) or 0
	if os.time() >= endsAt then endMatch() end
end

local function convertSpawn(part: BasePart): SpawnLocation
	local teamName = tostring(attr(part, "Team", "Blue"))
	local team = ensureTeam(teamName)
	-- If the generated scene already placed a SpawnLocation on this anchor
	-- (gameplay-pass adds per-team spawns statically), adopt it and assign the
	-- team rather than destroying the part — destroying it would also remove
	-- that child spawn and leave the team with no spawn point.
	local childSpawn = part:FindFirstChildOfClass("SpawnLocation")
	if childSpawn then
		childSpawn.Neutral = false
		childSpawn.TeamColor = team.TeamColor
		return childSpawn
	end
	local spawn = Instance.new("SpawnLocation")
	spawn.Name = part.Name
	spawn.Size = part.Size; spawn.CFrame = part.CFrame
	spawn.Anchored = true
	spawn.BrickColor = part.BrickColor; spawn.Material = part.Material
	spawn.Neutral = false
	spawn.TeamColor = team.TeamColor
	spawn.Parent = part.Parent
	part:Destroy()
	return spawn
end

local function wireTeamSpawns()
	for _, inst in CollectionService:GetTagged("TeamSpawn") do
		if inst:IsA("BasePart") then convertSpawn(inst) end
	end
end

local BLASTER_DAMAGE = 34          -- ~3 shots to down a 100 HP target
local BLASTER_RANGE  = 300
local BLASTER_COOLDOWN = 0.35

local function buildBlaster(): Tool
	local tool = Instance.new("Tool")
	tool.Name = "Blaster"; tool.RequiresHandle = true
	tool.CanBeDropped = false
	local handle = Instance.new("Part")
	handle.Name = "Handle"; handle.Size = Vector3.new(0.6, 0.6, 2.4)
	handle.BrickColor = BrickColor.new("Dark stone grey")
	handle.Material = Enum.Material.Metal
	handle.Parent = tool

	-- Server-side hitscan so the Blaster actually shoots. Activated fires when
	-- the holder clicks; we raycast forward from the handle, damage the first
	-- Humanoid hit (no friendly fire), and award the shooter on a kill. A short
	-- tracer gives visible feedback. This is the core FPS verb — without it the
	-- arena is just geometry with a prop in hand.
	local lastFire = 0
	tool.Activated:Connect(function()
		local now = os.clock()
		if now - lastFire < BLASTER_COOLDOWN then return end
		lastFire = now
		local char = tool.Parent
		local shooter = char and Players:GetPlayerFromCharacter(char)
		if not (char and shooter) then return end
		local muzzle = handle.Position
		local dir = handle.CFrame.LookVector * BLASTER_RANGE

		local params = RaycastParams.new()
		params.FilterType = Enum.RaycastFilterType.Exclude
		params.FilterDescendantsInstances = { char }
		local result = Workspace:Raycast(muzzle, dir, params)

		-- tracer
		local beam = Instance.new("Part")
		beam.Anchored = true; beam.CanCollide = false; beam.Material = Enum.Material.Neon
		beam.BrickColor = (shooter.Team and shooter.Team.TeamColor) or BrickColor.new("Bright yellow")
		local hitPos = result and result.Position or (muzzle + dir)
		beam.Size = Vector3.new(0.15, 0.15, (hitPos - muzzle).Magnitude)
		beam.CFrame = CFrame.lookAt(muzzle:Lerp(hitPos, 0.5), hitPos)
		beam.Parent = Workspace
		game:GetService("Debris"):AddItem(beam, 0.1)

		if not result then return end
		local hitChar = result.Instance.Parent
		local hum = hitChar and hitChar:FindFirstChildOfClass("Humanoid")
		if not hum or hum.Health <= 0 then return end

		-- No friendly fire between players on the same team.
		local victim = Players:GetPlayerFromCharacter(hitChar)
		if victim and victim.Team and shooter.Team and victim.Team == shooter.Team then return end

		hum:TakeDamage(BLASTER_DAMAGE)
		if hum.Health <= 0 then
			local _c, score, kills = ensureStats(shooter)
			kills.Value = kills.Value + 1
			score.Value = score.Value + 25
			if shooter.Team then
				addTeamScore(shooter.Team.Name, 25)
				local victimName = victim and victim.Name or "enemy"
				pushFeed(("%s [%s] eliminated %s"):format(shooter.Name, shooter.Team.Name, victimName), shooter.Team.Name)
			end
		end
	end)

	return tool
end

local function wireWeaponLocker(locker: BasePart)
	local team = tostring(attr(locker, "Team", "Blue"))
	local prompt = Instance.new("ProximityPrompt")
	prompt.ActionText = "Take " .. team .. " Blaster"
	prompt.HoldDuration = 0.4; prompt.MaxActivationDistance = 10
	prompt.Parent = locker
	prompt.Triggered:Connect(function(player)
		if player.Team and player.Team.Name ~= team then return end
		local character = player.Character
		if not character then return end
		local backpack = player:FindFirstChildOfClass("Backpack")
		if not backpack then return end
		if backpack:FindFirstChild("Blaster") or character:FindFirstChild("Blaster") then return end
		buildBlaster().Parent = backpack
	end)
end

local function returnFlag(flag: BasePart)
	local home = flagHome[flag]
	if home then flag.CFrame = home end
end

local function wireFlag(flag: BasePart)
	flagHome[flag] = flag.CFrame
	local flagTeam = tostring(attr(flag, "Team", "Blue"))
	flag.Touched:Connect(function(hit: BasePart)
		local character = hit.Parent
		local player = character and Players:GetPlayerFromCharacter(character)
		if not player or not player.Team then return end
		if player.Team.Name == flagTeam then
			returnFlag(flag)
			return
		end
		local captures, score = ensureStats(player)
		captures.Value = captures.Value + 1
		score.Value = score.Value + 100
		addTeamScore(player.Team.Name, 100)
		pushFeed(("%s [%s] captured the %s flag (+100)"):format(player.Name, player.Team.Name, flagTeam), player.Team.Name)
		returnFlag(flag)
	end)
end

type CapEntry = { team: string?, since: number, captureTime: number, bar: Frame?, label: TextLabel? }
local capState: { [BasePart]: CapEntry } = {}

local function attachCaptureGui(point: BasePart): (Frame, TextLabel)
	local bb = Instance.new("BillboardGui")
	bb.Name = "CaptureProgress"
	bb.AlwaysOnTop = true
	bb.Size = UDim2.new(0, 180, 0, 36)
	bb.StudsOffset = Vector3.new(0, 4, 0)
	bb.Parent = point
	local bg = Instance.new("Frame")
	bg.Size = UDim2.new(1, 0, 0.45, 0); bg.Position = UDim2.new(0, 0, 0.55, 0)
	bg.BackgroundColor3 = Color3.fromRGB(30, 30, 30); bg.BackgroundTransparency = 0.3
	bg.BorderSizePixel = 0; bg.Parent = bb
	local bar = Instance.new("Frame")
	bar.Name = "Bar"
	bar.Size = UDim2.new(0, 0, 1, 0)
	bar.BackgroundColor3 = Color3.fromRGB(180, 180, 180); bg.BorderSizePixel = 0
	bar.BorderSizePixel = 0; bar.Parent = bg
	local label = Instance.new("TextLabel")
	label.Name = "Label"
	label.Size = UDim2.new(1, 0, 0.55, 0); label.Position = UDim2.new(0, 0, 0, 0)
	label.BackgroundTransparency = 1
	label.TextColor3 = Color3.fromRGB(240, 240, 240); label.Font = Enum.Font.GothamBold
	label.TextScaled = true; label.Text = "Neutral"; label.Parent = bb
	return bar, label
end

local function wireCapturePoint(point: BasePart)
	local bar, label = attachCaptureGui(point)
	capState[point] = {
		team = nil, since = 0,
		captureTime = attr(point, "CaptureTime", 8),
		bar = bar, label = label,
	}
end

local function tickCapturePoints()
	for point, st in capState do
		local occupants: { [string]: number } = { Blue = 0, Red = 0 }
		-- Modern occupancy query. FindPartsInRegion3 was removed from Roblox;
		-- GetPartBoundsInBox + OverlapParams is the supported replacement and
		-- (unlike the old call wrapped in pcall) does not fail silently — so
		-- capture points actually score.
		local params = OverlapParams.new()
		params.FilterType = Enum.RaycastFilterType.Exclude
		params.FilterDescendantsInstances = { point }
		params.MaxParts = 50
		local parts = Workspace:GetPartBoundsInBox(point.CFrame, point.Size, params)
		local seen: { [Player]: boolean } = {}
		for _, p in parts do
			local character = p.Parent
			local player = character and Players:GetPlayerFromCharacter(character)
			if player and player.Team and not seen[player] then
				seen[player] = true
				occupants[player.Team.Name] = (occupants[player.Team.Name] or 0) + 1
			end
		end
		local soleTeam: string? = nil
		if occupants.Blue > 0 and occupants.Red == 0 then soleTeam = "Blue"
		elseif occupants.Red > 0 and occupants.Blue == 0 then soleTeam = "Red" end
		if soleTeam ~= st.team then
			st.team = soleTeam; st.since = os.clock()
		elseif soleTeam and (os.clock() - st.since) >= st.captureTime then
			point.BrickColor = TEAM_COLORS[soleTeam] or point.BrickColor
			for _, player in Players:GetPlayers() do
				if player.Team and player.Team.Name == soleTeam then
					local _c, score = ensureStats(player)
					score.Value = score.Value + 50
				end
			end
			addTeamScore(soleTeam, 50)
			pushFeed(("%s team captured %s (+50)"):format(soleTeam, point.Name), soleTeam)
			st.since = os.clock() + 5      -- cooldown before re-scoring
		end
		if st.bar and st.label then
			local progress = 0
			local txt = "Neutral"
			local col = Color3.fromRGB(180, 180, 180)
			if soleTeam then
				progress = math.clamp((os.clock() - st.since) / st.captureTime, 0, 1)
				col = TEAM_COLOR3[soleTeam] or col
				txt = ("%s capturing  %d%%"):format(soleTeam, math.floor(progress * 100))
			end
			(st.bar :: Frame).Size = UDim2.new(progress, 0, 1, 0)
			;(st.bar :: Frame).BackgroundColor3 = col
			;(st.label :: TextLabel).Text = txt
			;(st.label :: TextLabel).TextColor3 = col
		end
	end
end

local function onPlayerAdded(player: Player)
	ensureStats(player)
	player.Team = ensureTeam(smallerTeamName())
end

function FPSKit.start()
	assert(RunService:IsServer(), "[FPSKit] start() must run on the server.")
	if started then return end
	started = true

	ensureSharedState()
	ensureTeam("Blue"); ensureTeam("Red")
	wireTeamSpawns()
	for _, inst in CollectionService:GetTagged("WeaponLocker") do
		if inst:IsA("BasePart") then wireWeaponLocker(inst) end
	end
	for _, inst in CollectionService:GetTagged("Flag") do
		if inst:IsA("BasePart") then wireFlag(inst) end
	end
	for _, inst in CollectionService:GetTagged("CapturePoint") do
		if inst:IsA("BasePart") then wireCapturePoint(inst) end
	end

	Players.PlayerAdded:Connect(onPlayerAdded)
	for _, player in Players:GetPlayers() do task.spawn(onPlayerAdded, player) end

	task.spawn(function()
		while started do
			task.wait(0.5)
			pcall(tickCapturePoints)
			pcall(tickMatch)
		end
	end)

	print(("[FPSKit] Started.  Teams: Blue / Red  Cap: %d  Duration: %ds"):format(MATCH_SCORE_CAP, MATCH_DURATION))
end

return FPSKit`;
}

