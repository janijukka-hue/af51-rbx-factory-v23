function _stateReducer(targetId) {
  return `--!strict
-- AF51-RBX | ServerScriptService/Services/StateReducer.lua
local AuditRuntime = require(game.ReplicatedStorage:WaitForChild("Packages",15)
\t:WaitForChild("AF51Runtime",15):WaitForChild("AuditRuntime",15))

type Action = { type: string, payload: { [string]: any }? }

local function reducer(state: { [string]: any }, action: Action): { [string]: any }
\tlocal t = action.type
\tlocal p = action.payload or {}
\tif t == "INIT_PLAYER" then
\t\tstate.players = state.players or {}
\t\tstate.players[p.playerId] = p.data
\telseif t == "REMOVE_PLAYER" then
\t\tif state.players then state.players[p.playerId] = nil end
\telseif t == "ADD_COINS" then
\t\tif state.players and state.players[p.playerId] then
\t\t\tlocal amount = math.max(0, p.amount or 0)
\t\t\tstate.players[p.playerId].coins       = (state.players[p.playerId].coins or 0) + amount
\t\t\tstate.players[p.playerId].totalEarned = (state.players[p.playerId].totalEarned or 0) + amount
\t\tend
\telseif t == "SPEND_COINS" then
\t\tif state.players and state.players[p.playerId] then
\t\t\tlocal prev = state.players[p.playerId].coins or 0
\t\t\tstate.players[p.playerId].coins = math.max(0, prev - (p.amount or 0))
\t\tend
\telseif t == "UPGRADE_LEVEL" then
\t\tif state.players and state.players[p.playerId] then
\t\t\tstate.players[p.playerId].upgradeLevel = (state.players[p.playerId].upgradeLevel or 1) + 1
\t\tend
\telse
\t\tAuditRuntime.warn("[StateReducer] Unknown: " .. tostring(t), {})
\tend
\treturn state
end

return reducer`;
}

